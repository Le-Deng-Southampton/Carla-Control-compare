def arg_value(args, name):
    return getattr(args, name, DEFAULTS.get(name))


def arg_values(args, field_names):
    return [arg_value(args, name) for name in field_names]


def args_dict(args, field_pairs):
    return {key: arg_value(args, attr) for key, attr in field_pairs}


def controller_args_dict(args, controller_name):
    prefix = f"{controller_name}_"
    config = {}
    for attr in RUN_CONFIG_CONTROLLER_FIELDS[controller_name]:
        key = attr[len(prefix):] if attr.startswith(prefix) else attr
        config[key] = arg_value(args, attr)
    return config
